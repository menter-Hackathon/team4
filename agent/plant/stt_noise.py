"""STT のでっちあげ（無音・雑音から出てくる言葉）を見分ける（仕様 §8.2）。

Whisper 系の STT（kotoba-whisper など）は、無音や雑音しか無い音声からも、
「ごめん」「ご視聴ありがとうございました」のような言葉を作ってしまうことがある
（YouTube の字幕で学習しているため、動画の締めの言葉が出やすい）。
植物が起きている間に会場のざわざわを拾うと、この言葉に返事をしてしまう。
そこで、文字起こしがこうした言葉「だけ」のときは、発話として扱わない。

また、短い日本語の発話が韓国語（ハングル）で書き起こされることがある（#73）。
日本語の会話にハングルは出てこないので、1 文字でも入っていたら同じく扱わない。
"""

from __future__ import annotations

from .wake import normalize

# 文字起こしが丸ごとこれと同じなら、でっちあげとみなす。
# 「含むか」ではなく「同じか」で比べる。「ごめん、水忘れてた」のような本当の話しかけを捨てないため。
# 比べる前に normalize()（カタカナ→ひらがな、句読点の除去）でそろえるので、ここはひらがな・句読点なしで書く
HALLUCINATIONS = frozenset(
    normalize(t)
    for t in (
        # 2026-11-17・11-19 に、kotoba-whisper が無音・雑音から出した
        "ごめん",
        # 動画の締めの言葉。Whisper が無音から出しやすいことで知られている
        "ご視聴ありがとうございました",
        "ご視聴ありがとうございます",
        "チャンネル登録よろしくお願いします",
        "チャンネル登録お願いします",
    )
)


def has_hangul(text: str) -> bool:
    """ハングル（韓国語の文字）が 1 文字でも入っているか。

    例: "야호, 참다요." → True、"ちゃむだ요?" → True、"ちゃむだよ" → False
    """
    # 0xAC00〜0xD7A3: ハングルの音節（가〜힣）。0x1100〜0x11FF・0x3130〜0x318F: ハングルの字母
    return any("가" <= c <= "힣" or "ᄀ" <= c <= "ᇿ" or "㄰" <= c <= "㆏" for c in text)


def is_stt_noise(text: str) -> bool:
    """STT のでっちあげで、植物が返事をしてはいけない文字起こしか。

    引数:
        text: STT が文字起こしした文
    戻り値:
        でっちあげなら True。普通の発話（空の文も含む）なら False

    例: "ごめん。" → True、"ごめん、水忘れてた" → False、"야호" → True、"ありがとう" → False
    """
    return normalize(text) in HALLUCINATIONS or has_hangul(text)
