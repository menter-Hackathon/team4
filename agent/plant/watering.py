"""「お水あげたよ」を見分ける（仕様 §6.7、#81）。

なぜ声で水やりを記録するのか:
    本当は土の水分センサー（#58）で水やりを知りたかったが、筐体の都合で今回は見送った。
    その代わりに、持ち主が「お水あげたよ」と言ったことを水やりとして記録する。
    記録すると、植物がその場でお礼を言い、何日も水をもらえないと「のど渇いた」と言うようになる。

全体の流れ:
    1. 持ち主が話すたびに、conversation.py がこのファイルの mentions_watering() を呼ぶ
    2. True なら、conversation.py が DB（store.py の waterings テーブル）に 1 行記録し、
       「この会話で水をもらった。お礼を言う」入りのプロンプトに作り直す
    3. ここで見分けられなかった言い方（例:「ジョウロで湿らせといた」）は、
       眠ったあとの振り返り（reflection.py の watered）で LLM が拾う

なぜ LLM を使わずに、文字の並び（正規表現）で見分けるのか:
    持ち主が話すたびに LLM を呼ぶと、植物の返事が 1 秒近く遅くなる。
    「水」と「あげた」のような決まった言葉の並びなら、正規表現で一瞬で見分けられる。

正規表現の読み方（このファイルで使っている記号だけ）:
    A|B      … A または B
    (A|B)    … A または B を 1 まとまりにする
    .        … 何か 1 文字（ひらがな・漢字・記号のどれでも）
    .{0,2}?  … 何か 0〜2 文字（できるだけ短く）。「水を」「お水は」の「を」「は」などを飛ばすため
    (を)?    … 「を」があってもなくてもよい
    [？?]    … 全角の「？」か半角の「?」のどちらか
"""

from __future__ import annotations

import re

# --- 「もう水をあげた」と言っている形 ---
# 「水」のあとに「あげ・やっ・入れ」などが来て、そのあとに「もう済ませた」ことを表す語尾が続くもの。
#
# _DONE は、その「もう済ませた」語尾:
#   た   … あげた・やった・入れた
#   まし … あげました
#   とい … あげといた（「あげておいた」の話し言葉）
#   てお・ておい … あげておいた
_DONE = r"(た|まし|とい|てお|ておい)"

# 拾う言い方の例と、どの行が拾うか:
#   1 行目: 「お水あげたよ」「水やったよ」「お水をあげました」「水あげといた」「今日は水上げたよ」
#   2 行目: 「水を入れてあげたよ」（「入れて」と「あげた」の 2 つの動詞が続く形）
#   3 行目: 「水やりしたよ」「水やりをしました」「水やりしといた」
#   4 行目: 「水やり終わったよ」
# 「水」と動詞の間に入ってよいのは 2 文字まで（.{0,2}?）。長くすると「水たまりがあった」のような
# 関係ない文まで拾ってしまうため。f-string（rf"…"）の中では { } を {{ }} と 2 つ重ねて書く
_WATERED = re.compile(
    rf"水.{{0,2}}?(あげ|上げ|やっ|やり|入れ|いれ){_DONE}"
    rf"|水.{{0,2}}?(入れ|いれ)て(あげ|上げ){_DONE}"
    r"|水やり(を)?(し|やっ)(た|まし|とい|てお)"
    r"|水やり(終わ|おわ)"
)

# --- 「まだあげていない」「これからあげる」と言っている形 ---
# 「水」のすぐ後の動詞に、次の語尾が付いているもの:
#   てない・ていない・てなかった・なかった・ない … 「水あげてない」「水あげなかった」
#   ようか・よう … 「お水あげようか？」（これからの話）
#   る？ … 「お水あげる？」（聞いているだけ）
# これに当てはまったら、_WATERED に当てはまっても水やりとは数えない
_NOT_DONE = re.compile(
    r"水.{0,2}?(あげ|上げ|やっ|やら|やり)(て(い)?ない|てなかった|なかった|ない|ようか|よう|る[？?])"
)


def mentions_watering(text: str) -> bool:
    """発話が「水をあげた」と言っていれば True。

    引数:
        text: 持ち主の発話を文字起こししたもの
    例:
        "お水あげたよ"            → True
        "水やりしといた"          → True
        "水あげたけど、元気ないね" → True（「ない」は「水あげた」のすぐ後ではないので、あげたと判断）
        "お水あげようか？"        → False（これからの話）
        "水あげてない"            → False
        "水飲んだ"                → False（水の話だが、植物にあげてはいない）
    """
    # 1. 「まだあげていない」「これから」の形が「水」のすぐ後にあれば、あげていない。
    #    先にこちらを調べるのは、「水あげてない」が _WATERED の「水あげ…」にも
    #    当てはまりそうに見えるため（否定を先に除いておくと間違えにくい）
    if _NOT_DONE.search(text):
        return False
    # 2. 「もう済ませた」形がどこかにあれば、あげた。
    #    .search() は文のどこか一部でも当てはまれば結果を返し、無ければ None を返す
    return _WATERED.search(text) is not None
