"""「お水あげたよ」を見分ける（仕様 §6.7、#81）。

土の水分センサー（#58）は筐体の都合で見送ったので、水やりは声で記録する。
会話中の発話をここで調べ、水をあげたと言っていれば、その場で記録して植物にお礼を言わせる。
言い換えの取りこぼしは、眠ったあとの振り返り（reflection.py の watered）で拾う。

LLM を使わずに文字の並びで見分けるのは、返事を遅くしないため（毎回の発話で LLM を呼ぶと 1 秒近く増える）。
"""

from __future__ import annotations

import re

# 「水」のあとに、あげた・やった・入れた などの「もう済ませた」形が続くもの。
# 例: 「お水あげたよ」「水やったよ」「お水をあげました」「水あげといた」「水を入れてあげた」
# 「水」と動詞の間には「を」「は」など数文字だけ入ってよい（「水たまりがあった」を拾わないよう短くする）
_DONE = r"(た|まし|とい|てお|ておい)"
_WATERED = re.compile(
    rf"水.{{0,2}}?(あげ|上げ|やっ|やり|入れ|いれ){_DONE}"  # 水あげた・水やった・水を入れた
    rf"|水.{{0,2}}?(入れ|いれ)て(あげ|上げ){_DONE}"  # 水を入れてあげた
    r"|水やり(を)?(し|やっ)(た|まし|とい|てお)"  # 水やりした・水やりしといた
    r"|水やり(終わ|おわ)"  # 水やり終わった
)
# あげていないことを言っている形。「水あげてない」「水あげなかった」「お水あげる？」「あげようか」
_NOT_DONE = re.compile(
    r"水.{0,2}?(あげ|上げ|やっ|やら|やり)(て(い)?ない|てなかった|なかった|ない|ようか|よう|る[？?])"
)


def mentions_watering(text: str) -> bool:
    """発話が「水をあげた」と言っていれば True。

    例:
        "お水あげたよ"     → True
        "水やりしといた"   → True
        "お水あげようか？" → False（これから）
        "水あげてない"     → False
        "水飲んだ"         → False
    """
    # 1. あげていない・これからの形が「水」のすぐ後にあれば、あげていない
    if _NOT_DONE.search(text):
        return False
    # 2. もう済ませた形があれば、あげた
    return _WATERED.search(text) is not None
